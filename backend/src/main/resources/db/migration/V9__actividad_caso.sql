-- CU-05 Bandeja Técnicos: actividades que el Técnico registra mientras atiende el
-- caso (RN19, RN20) y ruta del reporte de atención que se genera al finalizar (AN04 # 2).

CREATE TABLE IF NOT EXISTS actividad_caso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caso     BIGINT NOT NULL REFERENCES caso(id),
    id_tecnico  VARCHAR(13) NOT NULL REFERENCES usuario(cui),
    detalle     VARCHAR(500) NOT NULL,
    fecha       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_actividad_caso ON actividad_caso(id_caso);

ALTER TABLE caso ADD COLUMN IF NOT EXISTS informe_atencion_ruta VARCHAR(500);
