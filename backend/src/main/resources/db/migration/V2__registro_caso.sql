-- CU-02 Registro de Caso y contrato mínimo para CU-03..CU-18

CREATE TABLE ciudadano (
    dpi         VARCHAR(13) PRIMARY KEY,
    nombre      VARCHAR(150) NOT NULL,
    telefono    VARCHAR(8) NOT NULL,
    correo      VARCHAR(150) NOT NULL
);

CREATE TABLE estado_caso (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE categoria (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(150) NOT NULL,
    id_departamento     BIGINT NOT NULL REFERENCES departamento(id),
    activo              BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE categoria_tipo_caso (
    id_categoria    BIGINT NOT NULL REFERENCES categoria(id),
    tipo_caso       VARCHAR(20) NOT NULL,
    PRIMARY KEY (id_categoria, tipo_caso)
);

CREATE TABLE caso (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_seguimiento      CHAR(12) NOT NULL UNIQUE,
    dpi                     VARCHAR(13) NOT NULL REFERENCES ciudadano(dpi),
    tipo_caso               VARCHAR(20) NOT NULL,
    id_categoria            BIGINT NOT NULL REFERENCES categoria(id),
    id_departamento         BIGINT NOT NULL REFERENCES departamento(id),
    direccion               VARCHAR(250) NOT NULL,
    descripcion             VARCHAR(2000) NOT NULL,
    id_estado               BIGINT NOT NULL REFERENCES estado_caso(id),
    informe_inicial_ruta    VARCHAR(500),
    ip_origen               VARCHAR(50) NOT NULL,
    create_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_tecnico              VARCHAR(13) REFERENCES usuario(cui)
);

CREATE TABLE evidencia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caso         BIGINT NOT NULL REFERENCES caso(id),
    tipo            VARCHAR(20) NOT NULL,
    nombre_archivo  VARCHAR(255) NOT NULL,
    content_type    VARCHAR(120) NOT NULL,
    tamano_bytes    BIGINT NOT NULL,
    ruta            VARCHAR(500) NOT NULL
);

CREATE TABLE token_verificacion_ciudadano (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpi                         VARCHAR(13) NOT NULL REFERENCES ciudadano(dpi),
    codigo_hash                 VARCHAR(150) NOT NULL,
    fecha_creacion              TIMESTAMP NOT NULL,
    fecha_expiracion            TIMESTAMP NOT NULL,
    usado                       BOOLEAN NOT NULL DEFAULT FALSE,
    token_sesion                VARCHAR(255) UNIQUE,
    fecha_expiracion_sesion     TIMESTAMP,
    sesion_usada                BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE correlativo_seguimiento (
    anio    INT PRIMARY KEY,
    ultimo  INT NOT NULL
);

CREATE TABLE bitacora_cambio (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion      VARCHAR(120) NOT NULL,
    usuario     VARCHAR(50) NOT NULL,
    id_caso     BIGINT REFERENCES caso(id),
    fecha       DATE NOT NULL,
    hora        TIME NOT NULL,
    ip_origen   VARCHAR(50) NOT NULL,
    detalle     VARCHAR(500)
);

CREATE TABLE notificacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento          VARCHAR(80) NOT NULL,
    destinatario    VARCHAR(150) NOT NULL,
    cuerpo          TEXT NOT NULL,
    resultado       VARCHAR(20) NOT NULL,
    intentos        INT NOT NULL,
    id_caso         BIGINT REFERENCES caso(id),
    create_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE motivo_rechazo (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motivo  VARCHAR(150) NOT NULL UNIQUE,
    activo  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_caso_dpi ON caso(dpi);
CREATE INDEX idx_caso_estado ON caso(id_estado);
CREATE INDEX idx_token_verificacion_dpi ON token_verificacion_ciudadano(dpi);
CREATE INDEX idx_bitacora_caso ON bitacora_cambio(id_caso);

